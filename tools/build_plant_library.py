#!/usr/bin/env python3
"""Build the bundled thumbnail set and the optional full reference pack.

Input (existing library):
    assets/images/plants/<class_id>_<slug>/*.jpg

Outputs:
    assets/images/plants_thumbs/<class_id>.webp   # bundled, ~400 px
    lib/plantThumbs.ts                            # static require map
    plant-pack/full/<class_id>/<n>.webp           # optional download
    plant-pack/manifest.json                      # files + checksums

The full pack is intentionally not committed; upload `plant-pack/` to R2/S3 and
point EXPO_PUBLIC_PLANT_PACK_URL at the manifest.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import json
import time
from pathlib import Path

from PIL import Image, ImageOps

IMAGE_SUFFIXES = {".jpg", ".jpeg", ".png", ".webp"}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--images-root", default="assets/images/plants")
    parser.add_argument("--thumbs-out", default="assets/images/plants_thumbs")
    parser.add_argument("--pack-out", default="plant-pack")
    parser.add_argument("--thumbs-module", default="lib/plantThumbs.ts")
    parser.add_argument("--thumb-width", type=int, default=400)
    parser.add_argument("--full-width", type=int, default=720)
    parser.add_argument("--thumb-quality", type=int, default=75)
    parser.add_argument("--full-quality", type=int, default=80)
    parser.add_argument("--max-per-class", type=int, default=5)
    parser.add_argument("--version", default="2026.11")
    parser.add_argument("--base-url", default="")
    parser.add_argument("--license", default="Wikipedia/Wikimedia contributors (CC BY-SA)")
    return parser.parse_args()


def write_webp(source: Path, destination: Path, width: int, quality: int) -> tuple[int, int, int]:
    destination.parent.mkdir(parents=True, exist_ok=True)
    with Image.open(source) as opened:
        image = ImageOps.exif_transpose(opened).convert("RGB")
        if image.width > width:
            height = round(image.height * width / image.width)
            image = image.resize((width, height), Image.Resampling.LANCZOS)
        image.save(destination, "WEBP", quality=quality, method=6)
        return image.width, image.height, destination.stat().st_size


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        while chunk := fh.read(1 << 20):
            digest.update(chunk)
    return digest.hexdigest()


def main() -> int:
    args = parse_args()
    images_root = Path(args.images_root)
    thumbs_root = Path(args.thumbs_out)
    pack_root = Path(args.pack_out)
    thumbs_root.mkdir(parents=True, exist_ok=True)
    pack_root.mkdir(parents=True, exist_ok=True)

    classes: dict[int, list[Path]] = {}
    for folder in sorted(images_root.iterdir()):
        if not folder.is_dir():
            continue
        try:
            class_id = int(folder.name.split("_", 1)[0])
        except ValueError:
            continue
        files = sorted(
            path for path in folder.iterdir() if path.suffix.lower() in IMAGE_SUFFIXES
        )
        if files:
            classes[class_id] = files[: args.max_per_class]

    module_dir = Path(args.thumbs_module).parent
    thumbs_rel = os.path.relpath(thumbs_root, module_dir).replace(os.sep, "/")

    thumbs_module: list[str] = [
        "// AUTO-GENERATED by tools/build_plant_library.py. Do not edit.",
        "",
        "export const PLANT_THUMBS: Record<number, number> = {",
    ]
    images: list[dict[str, object]] = []
    thumb_bytes = 0
    full_bytes = 0
    for class_id, files in sorted(classes.items()):
        thumb_path = thumbs_root / f"{class_id}.webp"
        width, height, size = write_webp(
            files[0], thumb_path, args.thumb_width, args.thumb_quality
        )
        thumb_bytes += size
        thumbs_module.append(
            f"    {class_id}: require('{thumbs_rel}/{class_id}.webp'),"
        )
        for index, source in enumerate(files):
            rel = f"full/{class_id}/{index}.webp"
            destination = pack_root / rel
            full_width, full_height, full_size = write_webp(
                source, destination, args.full_width, args.full_quality
            )
            full_bytes += full_size
            images.append(
                {
                    "class_id": class_id,
                    "path": rel,
                    "bytes": full_size,
                    "sha256": sha256(destination),
                    "width": full_width,
                    "height": full_height,
                    "license": args.license,
                    "thumb": f"{class_id}.webp",
                }
            )
    thumbs_module.append("};")
    thumbs_module.append("")
    Path(args.thumbs_module).parent.mkdir(parents=True, exist_ok=True)
    Path(args.thumbs_module).write_text("\n".join(thumbs_module) + "\n", encoding="utf-8")

    manifest = {
        "version": args.version,
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "base_url": args.base_url,
        "thumb_width": args.thumb_width,
        "full_width": args.full_width,
        "thumb_bytes": thumb_bytes,
        "full_bytes": full_bytes,
        "image_count": len(images),
        "class_count": len(classes),
        "images": images,
    }
    (pack_root / "manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8"
    )
    print(
        json.dumps(
            {
                "classes": len(classes),
                "images": len(images),
                "thumb_mb": round(thumb_bytes / 1048576, 1),
                "full_mb": round(full_bytes / 1048576, 1),
                "thumbs": str(thumbs_root),
                "pack": str(pack_root),
                "module": str(args.thumbs_module),
            },
            indent=2,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
